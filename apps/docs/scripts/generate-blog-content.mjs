import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { toHtml } from "hast-util-to-html";
import matter from "gray-matter";
import rehypeHighlight from "rehype-highlight";
import remarkGfm from "remark-gfm";
import remarkParse from "remark-parse";
import remarkRehype from "remark-rehype";
import { unified } from "unified";

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(appDir, "src/content/blog");
const outputFile = path.join(appDir, "src/lib/blog.generated.ts");

function toAsciiTsString(value) {
  return JSON.stringify(value).replace(/[^\x20-\x7e]/gu, (character) => {
    const codePoint = character.codePointAt(0);
    if (codePoint === undefined) return character;
    return `\\u{${codePoint.toString(16)}}`;
  });
}

async function getMdxFiles() {
  try {
    const entries = await readdir(contentDir, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && entry.name.endsWith(".mdx"))
      .map((entry) => entry.name)
      .sort((a, b) => a.localeCompare(b));
  } catch (error) {
    if (error && error.code === "ENOENT") return [];
    throw error;
  }
}

async function renderMarkdown(content) {
  const processor = unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkRehype)
    .use(rehypeHighlight, { aliases: { typescript: ["tsx"] } });

  const mdast = processor.parse(content);
  const hast = await processor.run(mdast);
  return toHtml(hast);
}

const files = await getMdxFiles();
const lines = [
  "// This file is generated by scripts/generate-blog-content.mjs.",
  "// Do not edit it manually.",
  "",
  "export const BLOG_POSTS = [",
];

for (const file of files) {
  const slug = file.replace(/\.mdx$/, "");
  const raw = await readFile(path.join(contentDir, file), "utf8");
  const { data, content } = matter(raw);
  const html = await renderMarkdown(content);
  lines.push("  {");
  lines.push(`    slug: ${toAsciiTsString(slug)},`);
  lines.push(`    frontmatter: ${toAsciiTsString(JSON.stringify(data))},`);
  lines.push(`    content: ${toAsciiTsString(content)},`);
  lines.push(`    html: ${toAsciiTsString(html)},`);
  lines.push("  },");
}

lines.push("] as const;", "");

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, lines.join("\n"));

console.log(`Generated ${path.relative(appDir, outputFile)} (${files.length} posts)`);
